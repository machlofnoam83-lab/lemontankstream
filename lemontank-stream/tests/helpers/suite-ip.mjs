#!/usr/bin/env node
/**
 * כתובת "מבקר" ייחודית לכל קובץ בדיקות.
 *
 * למה זה נחוץ: מכסת ההרשמה באתר היא **אמיתית** — 5 הרשמות לשעה לכל כתובת
 * IP, וזה נכון. אבל כל חבילות הבדיקות רצות מאותה מכונה (127.0.0.1), ולכן
 * בלי הפרדה הן "מתחרות" זו בזו על אותה מכסה, וחבילה שמגיעה אחרונה נכשלת
 * ב-429 — לא בגלל תקלה בקוד, אלא בגלל שההגנה עבדה.
 *
 * הפתרון: כל חבילה מציגה את עצמה ככתובת פנימית (10.x) אחרת. השרת מאמין
 * ל-X-Forwarded-For רק כשהוא מגיע מפרוקסי מהימן — ובסביבת הבדיקות זה המצב
 * (127.0.0.1). שום דבר לא מרוכך: המכסות נשארות בדיוק כפי שהן בפרודקשן,
 * פשוט כל חבילה היא "משתמש אחר".
 */
export function suiteIp(name) {
  let hash = 7;
  for (const char of String(name)) hash = (hash * 31 + char.charCodeAt(0)) % 65521;
  return `10.77.${(hash % 200) + 20}.${((hash * 3) % 200) + 20}`;
}
